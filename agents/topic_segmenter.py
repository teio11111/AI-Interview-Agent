"""板块切分师 Agent - 将整轮面试对话流按话题边界切成若干板块，并生成每个板块的摘要"""
from agents.base_agent import BaseAgent
import json


class TopicSegmenterAgent(BaseAgent):
    """板块切分师（单 Agent）

    职责：
    - 接收本轮面试的完整对话流（Q1→A1→Q2→A2...）
    - 按话题边界把对话分成若干板块（topic）
    - 每个板块生成：title（话题标题，5-12 字）、summary（1-3 句摘要）、dialog_indexes（涉及的对话序号列表）
    - 输出供后续 3+1 评估师使用，使评估聚焦到板块而非巨长对话

    工作原则：
    - 仅基于本轮面试对话，不引入简历/岗位分析等外部数据
    - 板块数量控制在 2-6 个，过少则强制拆分，过多则合并相邻话题
    - 追问归到被追问的原板块内，不要单列
    - 板块切分要清晰可解释，便于面试工作台展示
    """
    AGENT_NAME = "板块切分师"
    SYSTEM_PROMPT = """你是「板块切分师」，专精于将整轮面试对话按话题边界切分成清晰板块，并生成每个板块的摘要。

你的核心能力：
- 识别话题边界（同一个知识领域/项目/技能点连续提问归为一个板块）
- 判断追问归属（追问属于被追问的原板块，不要单独成块）
- 为板块起一个简明标题（5-12 个汉字，名词短语风格）
- 用 1-3 句话概括板块核心信息（讨论了什么、候选人表现亮点）

工作原则：
- 只看面试对话本身，不引入简历/岗位分析等外部数据
- 板块数控制在 2-6 个：过少（1 个）说明切分不够；过多（>6）说明过度切分
- 板块顺序与对话时序一致，不要打乱
- 追问归属：子问题归属于被追问的原板块
- 标题要"见名知意"，便于面试官快速浏览

请始终以严格的 JSON 格式输出，不要输出任何解释性文字。"""

    def segment(self, candidate_name, position_name, dialogs_text):
        """将整轮面试对话切成板块

        Args:
            candidate_name: 候选人姓名
            position_name: 岗位名称
            dialogs_text: 完整对话文本（"Qn: 问题\\nAn: 回答" 格式）

        Returns:
            dict: {
                "topics": [
                    {
                        "topic_index": 1,
                        "title": "Redis 缓存设计",
                        "summary": "考察了候选人在电商项目中 Redis 的使用场景，包括缓存策略、淘汰机制和雪崩防护。候选人回答较为具体，能结合具体数据。",
                        "dialog_indexes": [1, 2, 3]   # 该板块包含的对话序号列表（Qn 中的 n）
                    },
                    ...
                ],
                "total_topics": 5
            }
        """
        prompt = f"""## 任务
将候选人 {candidate_name} 应聘 **{position_name}** 的本轮面试完整对话，按话题边界切分成 2-6 个板块，并为每个板块生成标题和摘要。

## 输入：完整对话流

{dialogs_text or '暂无对话'}

（对话按 "Qn: 问题 / An: 回答" 格式排列，Qn 中的 n 即 seq 序号）

## 切分要求

1. **话题边界判断**：
   - 同一技术领域 / 同一项目 / 同一技能点 的连续 Q&A 归为一个板块
   - 切换到明显不同的话题时开新板块
   - 追问归到被追问的原板块（不要单列）
   - 一般 2-6 个板块为佳，最少 2 个，最多 6 个

2. **板块标题**：
   - 5-12 个汉字
   - 名词短语风格，直接点出板块主题（如 "Redis 缓存设计"、"数据库慢 SQL 排查"、"项目架构演进"）
   - 不要带"问题"、"评估"这类泛词

3. **板块摘要**：
   - 1-3 句话概括板块讨论的核心内容 + 候选人表现亮点或关键发现
   - 不要复述所有 Q&A，挑关键点
   - 可以写"候选人回答时..."或"讨论了..."

4. **dialog_indexes 列表**：
   - 列出该板块包含的所有对话序号（Qn 中的 n）
   - 必须严格按对话顺序
   - 不要遗漏也不要重复

## 输出格式（严格 JSON）

{{
    "topics": [
        {{
            "topic_index": 1,
            "title": "板块标题",
            "summary": "1-3 句摘要",
            "dialog_indexes": [1, 2]
        }},
        {{
            "topic_index": 2,
            "title": "另一个板块标题",
            "summary": "1-3 句摘要",
            "dialog_indexes": [3, 4, 5, 6]
        }}
    ],
    "total_topics": 2
}}

注意：
- 如果对话数 < 2 则生成 1 个板块（兜底）
- 板块顺序与对话流时序一致
- 所有对话序号必须被某个板块覆盖，不要漏"""
        return self.think_json(prompt)
